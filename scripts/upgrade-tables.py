#!/usr/bin/env python3
"""nostalre-client's upgrade packages (lib/game/src/upgrade_tables.rs) from rAthena's Renewal laphine_upgrade.yml.

An upgrade package (Booster Weapon Upgrade Package...) is used on one item of the bag: its script opens kRO's
upgrade window (`laphine_upgrade()`, ZC_RANDOM_UPGRADE_ITEM_UI_OPEN 0x0ab4), which says only which package was
used. kRO's client knows from its own data which items the package takes; this one reads the server's
laphine_upgrade.yml instead, so the window offers what the server accepts (clif_parse_laphine_upgrade's checks) and
says what the server does to it.

Usage: upgrade-tables.py [rathena dir] [output file]
"""

import sys
from pathlib import Path

from rathena_data import load_body

ROOT = Path(__file__).resolve().parent.parent
RATHENA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "server"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "client" / "lib" / "game" / "src" / "upgrade_tables.rs"
ITEM_DBS = ["item_db_usable.yml", "item_db_equip.yml", "item_db_etc.yml"]
# status.hpp's MAX_REFINE for Renewal: the server's default MaximumRefine, and its cap on every refine here
MAX_REFINE = 20
PER_LINE = 8


def main():
    items = {}
    for db in ITEM_DBS:
        for item in load_body(RATHENA / "db" / "re" / db):
            items[item["AegisName"].lower()] = item["Id"]
    groups = {g["Group"].lower() for g in load_body(RATHENA / "db" / "re" / "item_randomopt_group.yml")}

    def refine(entry, key, default=0):
        return min(int(entry.get(key, default)), MAX_REFINE)

    packages, skipped = {}, []
    for entry in load_body(RATHENA / "db" / "re" / "laphine_upgrade.yml"):
        names = [entry["Item"]] + [t["Item"] for t in entry.get("TargetItems") or []]
        group = entry.get("RandomOptionGroup")
        # an unknown item or option group drops the whole entry, as the server's loader does
        if any(n.lower() not in items for n in names) or (group and group.lower() not in groups):
            skipped.append(entry["Item"])
            continue
        package = items[entry["Item"].lower()]
        if package in packages:
            sys.exit(f"{entry['Item']} is listed twice; the server merges such entries, this script does not")
        packages[package] = {
            "targets": sorted({items[n.lower()] for n in names[1:]}),
            "min_refine": refine(entry, "MinimumRefine"),
            "max_refine": refine(entry, "MaximumRefine", MAX_REFINE),
            "cards_allowed": bool(entry.get("CardsAllowed", False)),
            "required_options": int(entry.get("RequiredRandomOptions", 0)),
            "result_refine": refine(entry, "ResultRefine"),
            "result_min": refine(entry, "ResultRefineMinimum"),
            "result_max": refine(entry, "ResultRefineMaximum"),
            "random_options": bool(group),
        }

    lines = [
        "// Generated by scripts/upgrade-tables.py from rAthena's db/re/laphine_upgrade.yml; do not edit.",
        "",
        "use crate::upgrade_package::UpgradeRule;",
        "",
        "/// (package item id, what it takes and does), in item id order",
        f"static PACKAGES: [(u32, UpgradeRule); {len(packages)}] = [",
    ]
    for package, p in sorted(packages.items()):
        lines.append(f"    ({package}, UpgradeRule {{")
        lines.append("        targets: &[")
        cells = [f"{t}," for t in p["targets"]]
        lines += ["            " + " ".join(cells[i : i + PER_LINE]) for i in range(0, len(cells), PER_LINE)]
        lines.append("        ],")
        for key in ("min_refine", "max_refine", "required_options", "result_refine", "result_min", "result_max"):
            lines.append(f"        {key}: {p[key]},")
        for key in ("cards_allowed", "random_options"):
            lines.append(f"        {key}: {'true' if p[key] else 'false'},")
        lines.append("    }),")
    lines += [
        "];",
        "",
        "/// An upgrade package's rule as the server's laphine_upgrade.yml has it, `None` for any other item",
        "pub fn upgrade_rule(package_id: u32) -> Option<&'static UpgradeRule> {",
        "    PACKAGES.binary_search_by_key(&package_id, |&(id, _)| id).ok().map(|i| &PACKAGES[i].1)",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    note = f" ({len(skipped)} skipped as the server skips them: {', '.join(skipped)})" if skipped else ""
    print(f"{OUT}: {len(packages)} upgrade packages{note}")


if __name__ == "__main__":
    main()
