#!/usr/bin/env python3
"""nostalre-client's selection boxes (lib/game/src/package_tables.rs) from rAthena's Renewal item_packages.yml.

A selection box (Metal Weapon Box...) opens a window of choices; the player's pick goes to the server as the choice's
number (CZ_USE_PACKAGEITEM, 0x0baf), and the server hands out what its own item_packages.yml lists under that number.
kRO's client draws the window from its own table (selectpackageitem_cln.lub); this one is read from the server's
data instead, so what the window shows is what the server gives. Each item comes with its kind as the server sends it
in the inventory (clif.cpp `itemtype`: shadow gear as a weapon or an armour, a pet egg as an armour).

Usage: package-tables.py [rathena dir] [output file]
"""

import sys
from pathlib import Path

from rathena_data import load_body, parse_enum

ROOT = Path(__file__).resolve().parent.parent
RATHENA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "server"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "client" / "lib" / "game" / "src" / "package_tables.rs"
ITEM_DBS = ["item_db_usable.yml", "item_db_equip.yml", "item_db_etc.yml"]
GRADES = {"NONE": 0, "D": 1, "C": 2, "B": 3, "A": 4}


def client_type(item, types):
    """The item's kind as the server sends it to the client (clif.cpp `itemtype`)"""
    kind = types["IT_" + item.get("Type", "Etc").upper()]
    if kind == types["IT_SHADOWGEAR"]:
        return types["IT_WEAPON"] if (item.get("Locations") or {}).get("Shadow_Weapon") else types["IT_ARMOR"]
    return types["IT_ARMOR"] if kind == types["IT_PETEGG"] else kind


def main():
    types = parse_enum(RATHENA / "src/common/mmo.hpp", "enum item_types", "IT_")
    items = {}
    for db in ITEM_DBS:
        for item in load_body(RATHENA / "db" / "re" / db):
            items[item["AegisName"].lower()] = item
    boxes = []
    for package in load_body(RATHENA / "db" / "re" / "item_packages.yml"):
        box = items[package["Item"].lower()]["Id"]
        choices = []
        for group in sorted(package["Groups"], key=lambda g: g["Group"]):
            entries = []
            for entry in group["Items"]:
                item = items[entry["Item"].lower()]
                entries.append(
                    "PackageItem { "
                    f"item_id: {item['Id']}, item_type: {client_type(item, types)}, "
                    f"amount: {entry.get('Amount', 1)}, rental_hours: {entry.get('RentalHours', 0)}, "
                    f"refine: {entry.get('Refine', 0)}, grade: {GRADES[str(entry.get('Grade', 'None')).upper()]}, "
                    f"random_option: {'true' if entry.get('RandomOptionGroup') else 'false'} }}"
                )
            choices.append((group["Group"], entries))
        boxes.append((box, choices))
    boxes.sort()

    lines = [
        "// Generated by scripts/package-tables.py from rAthena's db/re/item_packages.yml; do not edit.",
        "",
        "use crate::select_package::{PackageChoice, PackageItem};",
        "",
        "/// (box item id, its choices): the choices in the server's order, each with the number the server knows it by",
        f"static PACKAGES: [(u32, &[PackageChoice]); {len(boxes)}] = [",
    ]
    for box, choices in boxes:
        lines.append(f"    ({box}, &[")
        for group, entries in choices:
            lines.append(f"        PackageChoice {{ group: {group}, items: &[")
            lines += [f"            {entry}," for entry in entries]
            lines.append("        ] },")
        lines.append("    ]),")
    lines += [
        "];",
        "",
        "/// A selection box's choices as the server's item_packages.yml has them, `None` for any other item",
        "pub fn package_choices(box_id: u32) -> Option<&'static [PackageChoice]> {",
        "    PACKAGES.binary_search_by_key(&box_id, |&(id, _)| id).ok().map(|i| PACKAGES[i].1)",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(boxes)} selection boxes")


if __name__ == "__main__":
    main()
